// The printable-ASCII glyphs are Daniel Hepper's font8x8 (public domain,
// github.com/dhepper/font8x8, font8x8_basic.h), reproduced byte-for-byte.
// Its rows are LSB-first — bit 0 is the LEFTMOST pixel — and the tables
// here keep that order so they stay diffable against upstream; DrawChar's
// inner loop tests bit x rather than reversing the bytes.

