    /// <summary>Draw one codepoint with its top-left corner at (x, y).
    /// scale is an integer pixel multiplier (1 = 8x8 px, 2 = 16x16),
    /// nearest-neighbour — not a point size.</summary>
    public static void DrawChar(ScribblerHandle h, int cp, int x, int y,
                                int scale, byte r, byte g, byte b)
    {
        if (scale < 1) return;
        if (cp >= 32 && cp <= 126) DrawAscii(h, cp, x, y, scale, r, g, b);
        else if (cp >= 128 && cp <= 191) DrawSemigraphic(h, cp, x, y, scale, r, g, b);
        else if (cp >= 0x2500 && cp <= 0x253C) DrawBoxDrawing(h, cp, x, y, scale, r, g, b);
        // everything else: blank
    }

    /// <summary>Draw a string left-to-right, advancing a fixed 8 * scale
    /// per character — monospace, no kerning. Codepoint-aware, so box
    /// drawing outside the BMP surrogates would need would still be one
    /// cell (the covered ranges are all BMP anyway).</summary>
    public static void DrawText(ScribblerHandle h, string text, int x, int y,
                                int scale, byte r, byte g, byte b)
    {
        int cx = x;
        for (int i = 0; i < text.Length; i++)
        {
            int cp = char.ConvertToUtf32(text, i);
            if (char.IsHighSurrogate(text[i])) i++;
            DrawChar(h, cp, cx, y, scale, r, g, b);
            cx += 8 * scale;
        }
    }

    static void DrawAscii(ScribblerHandle h, int cp, int x, int y,
                          int scale, byte r, byte g, byte b)
    {
        int off = (cp - 32) * 8;
        for (int row = 0; row < 8; row++)
        {
            int bits = Ascii[off + row];
            if (bits == 0) continue;
            for (int col = 0; col < 8; col++)
                if ((bits >> col & 1) != 0)         // LSB-first: bit col = pixel col
                    FillCell(h, x + col * scale, y + row * scale, scale, scale, r, g, b);
        }
    }

    /// <summary>TRS-80 semigraphics, computed rather than looked up: the
    /// low 6 bits of the code say directly which of six sub-blocks are
    /// filled, in the TRS-80's own order (0=top-left, 1=top-right,
    /// 2=mid-left, 3=mid-right, 4=bottom-left, 5=bottom-right). The 8x8
    /// cell splits 4/4 across and 3/3/2 down.</summary>
    static void DrawSemigraphic(ScribblerHandle h, int cp, int x, int y,
                                int scale, byte r, byte g, byte b)
    {
        int bits = cp & 0x3F;
        Span<int> rowY = stackalloc int[] { 0, 3, 6 };   // band tops: 3/3/2 down
        Span<int> rowH = stackalloc int[] { 3, 3, 2 };
        for (int band = 0; band < 3; band++)
            for (int side = 0; side < 2; side++)         // 0=left, 1=right; 4/4 across
                if ((bits >> (band * 2 + side) & 1) != 0)
                    FillCell(h, x + side * 4 * scale, y + rowY[band] * scale,
                             4 * scale, rowH[band] * scale, r, g, b);
    }

    // Which of up/down/left/right arms reach the centre, per codepoint,
    // for the 11 light single-line glyphs. The rest of the box-drawing
    // block — double, heavy, dashed, arcs — renders blank.
    //                                 up     down   left   right
    static (bool U, bool D, bool L, bool R) BoxArms(int cp) => cp switch
    {
        0x2500 => (false, false, true, true),    // ─
        0x2502 => (true, true, false, false),    // │
        0x250C => (false, true, false, true),    // ┌
        0x2510 => (false, true, true, false),    // ┐
        0x2514 => (true, false, false, true),    // └
        0x2518 => (true, false, true, false),    // ┘
        0x251C => (true, true, false, true),     // ├
        0x2524 => (true, true, true, false),     // ┤
        0x252C => (false, true, true, true),     // ┬
        0x2534 => (true, false, true, true),     // ┴
        0x253C => (true, true, true, true),      // ┼
        _ => (false, false, false, false),
    };

    /// <summary>Light single-line box drawing, computed: 1px-wide (times
    /// scale) segments from the centre row/column (row 3, column 3 of the
    /// 8x8 cell) out to whichever edges the glyph's arms reach.</summary>
    static void DrawBoxDrawing(ScribblerHandle h, int cp, int x, int y,
                               int scale, byte r, byte g, byte b)
    {
        var (up, down, left, right) = BoxArms(cp);
        if (!(up || down || left || right)) return;
        const int c = 3;                              // centre row/column
        if (up) FillCell(h, x + c * scale, y, scale, (c + 1) * scale, r, g, b);
        if (down) FillCell(h, x + c * scale, y + c * scale, scale, (8 - c) * scale, r, g, b);
        if (left) FillCell(h, x, y + c * scale, (c + 1) * scale, scale, r, g, b);
        if (right) FillCell(h, x + c * scale, y + c * scale, (8 - c) * scale, scale, r, g, b);
    }

    static void FillCell(ScribblerHandle h, int x, int y, int w, int hgt,
                         byte r, byte g, byte b)
    {
        for (int dy = 0; dy < hgt; dy++)
            for (int dx = 0; dx < w; dx++)
                h.SetPixelClamped(x + dx, y + dy, r, g, b);
    }
}
